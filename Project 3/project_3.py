import pandas as pd
import numpy as np

df=pd.read_csv("/content/raw_skills.csv")
print(df.head())
print("Total roles: ",len(df))

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

vect=TfidfVectorizer()
matrix=vect.fit_transform(df["skills"])
print("Matrix shape:",matrix.shape)
print(vect.get_feature_names_out())

tfid_df=pd.DataFrame(matrix.toarray(),index=df["role"],columns=vect.get_feature_names_out())
row=tfid_df.loc["Data Scientist"]
print(row[row>0].sort_values(ascending=False).round(3))

inp=input("Enter at least 3 skills (seperated by commas): ")
inp_skills=[s.strip().lower() for s in inp.split(",") if s.strip()]

if len(inp_skills)<3:
  print("Please enter at least 3 skills")
else:
  inp_text=" ".join(inp_skills)
  inp_vector=vect.transform([inp_text])

  names=vect.get_feature_names_out()
  recognized=[names[i] for i in inp_vector.nonzero()[1]]

  print("Your skills: ",inp_skills)
  print("Vector shape: ",inp_vector.shape)
  print("recognized words: ",recognized)

from sklearn.metrics.pairwise import cosine_similarity

score=cosine_similarity(inp_vector,matrix)
print("Score shape: ",score.shape)

df["score"]=score[0]
print(df[["role","score"]])

rank=df.sort_values(by="score",ascending=False)
top3=rank.head(3)

print("Top 3 recommendations:\n")
for i,(_,row) in enumerate(top3.iterrows(),start=1):
  print(f"{i}.{row["role"]}-{row["score"]*100:.1f}%match")

"""making whole pipeline as a function"""

def recommend(user_input, top_n=3):
    skills = [s.strip().lower() for s in user_input.split(",") if s.strip()]

    if len(skills) < 3:
        print("Please enter at least 3 skills.")
        return

    user_text = " ".join(skills)
    user_vector = vect.transform([user_text])


    if user_vector.nnz == 0:
        print("Sorry, none of your skills matched our dataset.")
        print("Try skills like: python, sql, docker, aws, react, java")
        return


    vocab = set(vect.get_feature_names_out())
    unknown = [w for w in user_text.split() if w not in vocab]
    if unknown:
        print("Note: these words were not recognized:", unknown)


    scores = cosine_similarity(user_vector, matrix)[0]


    result = df[["role"]].copy()
    result["score"] = scores
    top = result.sort_values("score", ascending=False).head(top_n)
    top = top[top["score"] > 0]

    print(f"\nTop {len(top)} recommendations:\n")
    for i, (_, row) in enumerate(top.iterrows(), start=1):
        print(f"{i}. {row['role']} - {row['score'] * 100:.1f}% match")

recommend(input("Enter at least 3 skills (comma-seperated): "))