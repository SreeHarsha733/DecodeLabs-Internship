import cv2
import numpy as np
import pytesseract
import matplotlib.pyplot as plt
from pytesseract import Output
from google.colab import files

CONF_THRESHOLD = 80
DESKEW = True


uploaded = files.upload()
image_path = list(uploaded.keys())[0]
original = cv2.imread(image_path)
if original is None:
    raise ValueError("Could not read the file. Upload a .png or .jpg image.")
print("Image shape (H, W, C):", original.shape, "| data points:", original.size)

h, w = original.shape[:2]
if max(h, w) < 1200:
    scale = 1200 / max(h, w)
    original = cv2.resize(original, None, fx=scale, fy=scale, interpolation=cv2.INTER_CUBIC)


def deskew(img, max_angle=10, step=0.5):
    """Find the rotation that makes text rows sharpest, then straighten the image."""
    g = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    inv = cv2.threshold(g, 0, 255, cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)[1]
    hh, ww = inv.shape
    center = (ww // 2, hh // 2)
    best_angle, best_score = 0.0, -1.0
    for angle in np.arange(-max_angle, max_angle + step, step):
        M = cv2.getRotationMatrix2D(center, angle, 1.0)
        rot = cv2.warpAffine(inv, M, (ww, hh), flags=cv2.INTER_NEAREST)
        score = np.var(rot.sum(axis=1))
        if score > best_score:
            best_angle, best_score = angle, score
    M = cv2.getRotationMatrix2D(center, best_angle, 1.0)
    fixed = cv2.warpAffine(img, M, (ww, hh), flags=cv2.INTER_CUBIC,
                           borderMode=cv2.BORDER_REPLICATE)
    return fixed, best_angle

work = original.copy()
if DESKEW:
    work, angle = deskew(work)
    print(f"Deskew angle applied: {angle:.1f} degrees")

gray = cv2.cvtColor(work, cv2.COLOR_BGR2GRAY)
blur = cv2.GaussianBlur(gray, (5, 5), 0)
adaptive = cv2.adaptiveThreshold(blur, 255, cv2.ADAPTIVE_THRESH_GAUSSIAN_C,
                                 cv2.THRESH_BINARY, 31, 15)
otsu_cutoff, otsu = cv2.threshold(blur, 0, 255,
                                  cv2.THRESH_BINARY + cv2.THRESH_OTSU)
print("Otsu cutoff value:", otsu_cutoff)


def run_ocr(img, psm):
    cfg = f"--oem 3 --psm {psm}"
    d = pytesseract.image_to_data(img, config=cfg, output_type=Output.DICT)
    words = []
    for i, text in enumerate(d["text"]):
        text = text.strip()
        try:
            conf = float(d["conf"][i])
        except ValueError:
            conf = -1
        if text and conf >= 0:
            words.append(dict(text=text, conf=conf, x=d["left"][i], y=d["top"][i],
                              w=d["width"][i], h=d["height"][i]))
    return words

candidates = {"gray": gray, "adaptive": adaptive, "otsu": otsu}
results = []
print(f"\n{'image':<10}{'psm':<5}{'words':<7}{'mean conf':<10}")
for name, img in candidates.items():
    for psm in (3, 6, 11):
        words = run_ocr(img, psm)
        mean_conf = np.mean([wd["conf"] for wd in words]) if words else 0
        results.append(dict(name=name, psm=psm, words=words, mean=mean_conf))
        print(f"{name:<10}{psm:<5}{len(words):<7}{mean_conf:<10.1f}")

max_words = max(len(r["words"]) for r in results)
valid = [r for r in results if len(r["words"]) >= 0.8 * max_words]
best = max(valid, key=lambda r: r["mean"])
print(f"\nBest setting: image={best['name']}, psm={best['psm']}, "
      f"mean confidence={best['mean']:.1f}%")


kept = [wd for wd in best["words"] if wd["conf"] >= CONF_THRESHOLD]
dropped = len(best["words"]) - len(kept)
print(f"Words kept (>= {CONF_THRESHOLD}%): {len(kept)} | dropped: {dropped}")

full_text = pytesseract.image_to_string(candidates[best["name"]],
                                        config=f"--oem 3 --psm {best['psm']}")
print("\n----- EXTRACTED TEXT -----")
print(full_text.strip())
print("--------------------------")


result_img = work.copy()
font_scale = max(0.5, work.shape[1] / 2000)
thick = max(1, int(font_scale * 2))
for wd in kept:
    x, y, ww, hh = wd["x"], wd["y"], wd["w"], wd["h"]
    cv2.rectangle(result_img, (x, y), (x + ww, y + hh), (0, 180, 0), thick)
    cv2.putText(result_img, f"{wd['conf']:.0f}%", (x, max(15, y - 5)),
                cv2.FONT_HERSHEY_SIMPLEX, font_scale * 0.6, (0, 0, 255), thick)

fig, axes = plt.subplots(2, 3, figsize=(18, 11))
panels = [
    (cv2.cvtColor(original, cv2.COLOR_BGR2RGB), "1. Original", None),
    (gray, "2. Grayscale", "gray"),
    (blur, "3. Gaussian Blur", "gray"),
    (adaptive, "4. Adaptive Threshold", "gray"),
    (otsu, f"5. Otsu Threshold (cutoff {otsu_cutoff:.0f})", "gray"),
    (cv2.cvtColor(result_img, cv2.COLOR_BGR2RGB), f"6. OCR Result (words >= {CONF_THRESHOLD}%)", None),
]
for ax, (im, title, cmap) in zip(axes.ravel(), panels):
    ax.imshow(im, cmap=cmap)
    ax.set_title(title)
    ax.axis("off")
plt.tight_layout()
plt.savefig("pipeline_overview.png", dpi=120)
plt.show()

cv2.imwrite("ocr_result.png", result_img)
with open("ocr_text.txt", "w", encoding="utf-8") as f:
    f.write(full_text)


checks = {
    "1. Library integration (pytesseract ran without errors)": len(best["words"]) > 0,
    "2. Pre-processing (grayscale + adaptive threshold executed)": adaptive is not None,
    f"3. Accuracy (mean confidence >= {CONF_THRESHOLD}%)": best["mean"] >= CONF_THRESHOLD,
    "4. Visual confirmation (boxes + text output generated)": len(kept) > 0 and len(full_text.strip()) > 0,
}
print("\n===== GATEKEEPER RULE: MILESTONE VALIDATION =====")
for label, ok in checks.items():
    print(("[PASS] " if ok else "[FAIL] ") + label)
print(f"Final mean confidence: {best['mean']:.1f}%")